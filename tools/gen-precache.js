// pwa: regenerates the precache list + version inside sw.js (between the PRECACHE markers).
// Usage: node tools/gen-precache.js          rewrite sw.js
//        node tools/gen-precache.js --check  exit 1 if sw.js is stale (list or version)
//        node tools/gen-precache.js --list   print the list
// Every run also reports the precache size (what a first visit downloads for offline play).
// Scans the repo for the shipped game: index.html, manifest.webmanifest, css/, js/, assets/.
// Excludes tools/, node_modules/, .worktrees/, .git/, .github/, docs (.md/.txt) and dotfiles.
// The version is a hash of every precached file (plus sw.js's own logic), so any shipped change
// gives a new cache name -> the service worker updates and the "new version" toast appears.
// Run it after changing any game file (the Pages workflow also runs it before deploying).
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');
const SW = path.join(ROOT, 'sw.js');
const TOP_FILES = ['index.html', 'manifest.webmanifest'];
const DIRS = ['css', 'js', 'assets'];
const SKIP_DIRS = new Set(['tools', 'node_modules', '.worktrees', '.git', '.github']);
const SKIP_EXT = new Set(['.md', '.txt', '.map', '.psd', '.xcf', '.log']);
const TEXT_EXT = new Set(['.html', '.css', '.js', '.json', '.svg', '.webmanifest']);
const RE = /\/\/ <precache>[\s\S]*?\/\/ <\/precache>/;
const lf = s => s.split('\r\n').join('\n');

function walk(rel, out) {
  const abs = path.join(ROOT, rel);
  for (const ent of fs.readdirSync(abs, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : 1)) {
    if (ent.name.startsWith('.')) continue;
    const r = rel + '/' + ent.name;
    if (ent.isDirectory()) { if (!SKIP_DIRS.has(ent.name)) walk(r, out); }
    else if (ent.isFile() && !SKIP_EXT.has(path.extname(ent.name).toLowerCase())) out.push(r);
  }
  return out;
}

// text files hash with LF line endings so a Windows checkout (autocrlf) and CI agree on the version
function bytes(f) {
  const buf = fs.readFileSync(path.join(ROOT, f));
  return TEXT_EXT.has(path.extname(f).toLowerCase()) ? lf(buf.toString('utf8')) : buf;
}

function collect() {
  const files = TOP_FILES.filter(f => fs.existsSync(path.join(ROOT, f)));
  for (const d of DIRS) if (fs.existsSync(path.join(ROOT, d))) walk(d, files);
  const h = crypto.createHash('sha256');
  for (const f of files) { h.update(f + '\0'); h.update(bytes(f)); }
  // the worker's own logic counts too (minus the generated block, which holds the version itself)
  if (fs.existsSync(SW)) h.update(lf(fs.readFileSync(SW, 'utf8')).replace(RE, ''));
  const bytesTotal = files.reduce((n, f) => n + fs.statSync(path.join(ROOT, f)).size, 0);
  return { files, version: h.digest('hex').slice(0, 12), bytes: bytesTotal };
}

function block({ files, version }) {
  return '// <precache> generated by tools/gen-precache.js - do not edit by hand\n' +
    "const VERSION = '" + version + "';\n" +
    'const PRECACHE = [\n' + files.map(f => "  '" + f + "',").join('\n') + '\n];\n' +
    '// </precache>';
}

const mb = b => (b / 1048576).toFixed(2) + ' MB';

function main() {
  const arg = process.argv[2] || '';
  const data = collect();
  if (arg === '--list') { console.log(data.files.join('\n')); return; }
  const src = fs.readFileSync(SW, 'utf8');
  if (!RE.test(src)) { console.error('sw.js has no // <precache> ... // </precache> block'); process.exit(2); }
  const next = src.replace(RE, () => block(data));
  if (arg === '--check') {
    if (lf(next) !== lf(src)) { console.error('sw.js precache is STALE - run: node tools/gen-precache.js'); process.exit(1); }
    console.log('sw.js precache up to date (' + data.files.length + ' files, ' + mb(data.bytes) + ', version ' + data.version + ')');
    return;
  }
  if (next !== src) fs.writeFileSync(SW, next);
  console.log((next !== src ? 'updated' : 'unchanged') + ' sw.js: ' + data.files.length + ' files, ' + mb(data.bytes) + ', version ' + data.version);
}
if (require.main === module) main();
module.exports = { collect, RE };
